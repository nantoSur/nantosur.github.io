const STORAGE_KEY = "portfolio-lang";
const supportedLanguages = ["id", "en"];

function readStoredLanguage() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    return supportedLanguages.includes(stored) ? stored : null;
  } catch (error) {
    return null;
  }
}

function storeLanguage(lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch (error) {
    // localStorage bisa diblokir saat file dibuka langsung; abaikan.
  }
}

let currentLang = readStoredLanguage() || "id";

const t = (key) => translations[currentLang]?.[key] ?? translations.id[key] ?? key;

const header = document.querySelector("#header");
const menuToggle = document.querySelector(".menu-toggle");
const navPanel = document.querySelector("#nav-panel");
const hero = document.querySelector(".hero");
const heroVisual = document.querySelector(".hero-visual");
const player = document.querySelector("#player");
const playBtn = document.querySelector("#playBtn");

function updatePlayButton() {
  if (!playBtn) return;
  const playing = Boolean(player?.classList.contains("is-playing"));
  playBtn.setAttribute("aria-label", t(playing ? "player.pause" : "player.play"));
  playBtn.setAttribute("aria-pressed", String(playing));
}

function setMenu(open) {
  navPanel?.classList.toggle("is-open", open);
  menuToggle?.setAttribute("aria-expanded", String(open));
  menuToggle?.setAttribute("aria-label", t(open ? "common.menuClose" : "common.menuOpen"));
}

function applyLanguage(lang) {
  if (!supportedLanguages.includes(lang)) return;

  currentLang = lang;
  document.documentElement.lang = lang;
  document.title = t("meta.title");

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", t(element.dataset.i18nAria));
  });

  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    element.setAttribute("content", t(element.dataset.i18nContent));
  });

  document.querySelectorAll("[data-lang-btn]").forEach((button) => {
    const active = button.dataset.langBtn === lang;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  updatePlayButton();
  setMenu(navPanel?.classList.contains("is-open") ?? false);
  storeLanguage(lang);
}

// Header shadow on scroll
const onScroll = () => header?.classList.toggle("is-scrolled", window.scrollY > 12);
onScroll();
window.addEventListener("scroll", onScroll, { passive: true });

// Mobile menu
menuToggle?.addEventListener("click", () => {
  setMenu(menuToggle.getAttribute("aria-expanded") !== "true");
});

navPanel?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => setMenu(false));
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") setMenu(false);
});

document.addEventListener("click", (event) => {
  if (!navPanel?.contains(event.target) && !menuToggle?.contains(event.target)) {
    setMenu(false);
  }
});

// Language switcher
document.querySelectorAll("[data-lang-btn]").forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.langBtn);
    setMenu(false);
  });
});

// Reveal on scroll
const revealItems = document.querySelectorAll("[data-reveal]");

if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -8% 0px" }
  );

  revealItems.forEach((item) => observer.observe(item));

  // Pastikan konten di atas lipatan tetap tampil walau observer tertunda.
  revealItems.forEach((item) => {
    if (item.getBoundingClientRect().top < window.innerHeight * 0.95) {
      item.classList.add("is-visible");
    }
  });
} else {
  revealItems.forEach((item) => item.classList.add("is-visible"));
}

// Subtle parallax on the hero player
hero?.addEventListener("pointermove", (event) => {
  const rect = hero.getBoundingClientRect();
  const x = (event.clientX - rect.left) / rect.width - 0.5;
  const y = (event.clientY - rect.top) / rect.height - 0.5;
  heroVisual?.style.setProperty("--mx", x.toFixed(3));
  heroVisual?.style.setProperty("--my", y.toFixed(3));
});

hero?.addEventListener("pointerleave", () => {
  heroVisual?.style.setProperty("--mx", 0);
  heroVisual?.style.setProperty("--my", 0);
});

// Work-card tilt
document.querySelectorAll(".work-card").forEach((card) => {
  card.addEventListener("pointermove", (event) => {
    const rect = card.getBoundingClientRect();
    const x = (event.clientX - rect.left) / rect.width - 0.5;
    const y = (event.clientY - rect.top) / rect.height - 0.5;
    card.style.setProperty("--rx", (x * 2).toFixed(3));
    card.style.setProperty("--ry", (y * 2).toFixed(3));
  });

  card.addEventListener("pointerleave", () => {
    card.style.setProperty("--rx", 0);
    card.style.setProperty("--ry", 0);
  });
});

// Demo play button for the featured-project "player"
playBtn?.addEventListener("click", () => {
  player?.classList.toggle("is-playing");
  updatePlayButton();
});

// Footer year
const year = document.querySelector("#year");
if (year) year.textContent = String(new Date().getFullYear());

applyLanguage(currentLang);
